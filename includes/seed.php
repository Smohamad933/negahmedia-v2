/**
 * درج داده‌های پیش‌فرض (فقط اگر جدول‌ها خالی باشند).
 */
function seed_all(bool $force = false): void
{
    /* --- تنظیمات --- */
    $hasSettings = (int) qv('SELECT COUNT(*) FROM `settings`', [], 0) > 0;
    if ($force || !$hasSettings) {
        foreach (seed_settings() as $k => $v) {
            setting_save((string) $k, (string) $v);
        }
    }

    /* --- آمار --- */
    if ($force || (int) qv('SELECT COUNT(*) FROM `stats`', [], 0) === 0) {
        foreach (seed_stats() as $row) {
            db_run('INSERT INTO `stats` (`value`,`label`,`sort_order`) VALUES (?,?,?)', $row);
        }
    }

    /* --- خدمات --- */
    if ($force || (int) qv('SELECT COUNT(*) FROM `services`', [], 0) === 0) {
        foreach (seed_services() as $row) {
            db_run('INSERT INTO `services` (`title`,`description`,`sort_order`) VALUES (?,?,?)', $row);
        }
    }

    /* --- مراحل همکاری --- */
    if ($force || (int) qv('SELECT COUNT(*) FROM `process_steps`', [], 0) === 0) {
        foreach (seed_process() as $row) {
            db_run('INSERT INTO `process_steps` (`title`,`description`,`sort_order`) VALUES (?,?,?)', $row);
        }
    }

    /* --- دسته‌ها و همراهان --- */
    if ($force || (int) qv('SELECT COUNT(*) FROM `client_groups`', [], 0) === 0) {
        $groupIds = [];
        foreach (seed_client_groups() as $row) {
            $groupIds[] = db_run('INSERT INTO `client_groups` (`title`,`subtitle`,`sort_order`) VALUES (?,?,?)', $row);
        }
        foreach (seed_clients() as $groupIndex => $names) {
            $gid = $groupIds[$groupIndex] ?? ($groupIds[0] ?? 0);
            $order = 1;
            foreach ($names as $name) {
                db_run(
                    'INSERT INTO `clients` (`group_id`,`name`,`sort_order`) VALUES (?,?,?)',
                    [$gid, $name, $order++]
                );
            }
        }
    }
}
